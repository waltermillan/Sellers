-- 1. SELLER
CREATE TABLE T_SELLER (
    ID       NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NAME     VARCHAR2(50),
    BIRTHDAY TIMESTAMP(6),
    CONSTRAINT PK_T_SELLER PRIMARY KEY (ID)
);

-- 2. BUYER
CREATE TABLE T_BUYER (
    ID                     NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NAME                   VARCHAR2(100) NOT NULL,
    SOCIAL_SECURITY_NUMBER NUMBER(10,0),
    CONSTRAINT PK_T_BUYER PRIMARY KEY (ID)
);

-- 3. PRODUCT
CREATE TABLE T_PRODUCT (
    ID             NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NAME           VARCHAR2(100) NOT NULL,
    PACKAGING_DATE TIMESTAMP(6) NOT NULL,
    STOCK          NUMBER(10,0) NOT NULL,
    PRICE          NUMBER(9,2) NOT NULL,
    CONSTRAINT PK_T_PRODUCT PRIMARY KEY (ID)
);

-- 4. USER
CREATE TABLE T_USER (
    ID            NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    USERNAME      VARCHAR2(255) NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    CREATED_AT    TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT    TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_T_USER PRIMARY KEY (ID),
    CONSTRAINT UQ_T_USER_USERNAME UNIQUE (USERNAME)
);

-- 5. SALE
CREATE TABLE T_SALE (
    ID         NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ID_SELLER  NUMBER(10,0) NOT NULL,
    ID_PRODUCT NUMBER(10,0) NOT NULL,
    ID_BUYER   NUMBER(10,0) NOT NULL,
	AMOUNT	   NUMBER(10,0) NOT NULL,
	QUANTITY   NUMBER(10,0) NOT NULL,
    SALE_DATE  DATE NOT NULL,
    CONSTRAINT PK_T_SALE PRIMARY KEY (ID),
    CONSTRAINT FK_SALE_PRODUCT
        FOREIGN KEY (ID_PRODUCT) REFERENCES T_PRODUCT (ID),
    CONSTRAINT FK_SALE_SELLER
        FOREIGN KEY (ID_SELLER) REFERENCES T_SELLER (ID),
    CONSTRAINT FK_SALE_BUYER
        FOREIGN KEY (ID_BUYER) REFERENCES T_BUYER (ID)
);

